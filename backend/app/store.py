"""Repository interface. The service layer only talks to this, so the storage can be
swapped: MemoryStore (iteration 3) → SqlStore with SQLAlchemy (iteration 4).
Rows are plain dicts with the field names used below."""
from abc import ABC, abstractmethod


class Store(ABC):
    # users / sessions
    @abstractmethod
    def add_user(self, email, name, password_hash) -> dict: ...
    @abstractmethod
    def user_by_email(self, email) -> dict | None: ...
    @abstractmethod
    def user_by_token(self, token) -> dict | None: ...
    @abstractmethod
    def add_session(self, token, user_id): ...
    @abstractmethod
    def delete_session(self, token): ...
    # quizzes
    @abstractmethod
    def add_quiz(self, owner_id, title, description, questions, updated_at) -> dict: ...
    @abstractmethod
    def update_quiz(self, quiz_id, title, description, questions, updated_at) -> dict: ...
    @abstractmethod
    def delete_quiz(self, quiz_id): ...
    @abstractmethod
    def quiz(self, quiz_id) -> dict | None: ...
    @abstractmethod
    def quizzes_of(self, owner_id) -> list[dict]: ...
    # games
    @abstractmethod
    def add_game(self, **fields) -> dict: ...
    @abstractmethod
    def game(self, game_id) -> dict | None: ...
    @abstractmethod
    def open_game_by_pin(self, pin) -> dict | None: ...
    @abstractmethod
    def update_game(self, game_id, **fields): ...
    @abstractmethod
    def games_of(self, host_id) -> list[dict]: ...
    # players / answers
    @abstractmethod
    def add_player(self, game_id, nickname, token) -> dict: ...
    @abstractmethod
    def players_of(self, game_id) -> list[dict]: ...
    @abstractmethod
    def player_by_token(self, game_id, token) -> dict | None: ...
    @abstractmethod
    def update_player(self, player_id, **fields): ...
    @abstractmethod
    def add_answer(self, **fields): ...
    @abstractmethod
    def answers_of(self, game_id, question_index=None) -> list[dict]: ...
